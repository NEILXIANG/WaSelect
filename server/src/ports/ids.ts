/**
 * 职责：**标识符生成端口**（F10 最后一项）——把"摇号"从全局函数变成**可注入的输入**。
 *
 * @why 与 `ports/clock.ts` 同一条理由的另一半：时间和随机数是仅有的两个
 *      "看着像纯函数、其实依赖全局状态"的输入。它们共同的特点是——
 *      **不注入的话，涉及它们的分支就只能靠运气覆盖**：
 *      - 单号冲突（D32 的重试路径）要等真实随机撞上一次才会走，概率约 1/10 亿；
 *      - 想在测试里断言"这张单的 id 是什么"，不注入就只能先解析响应再回查。
 *      注入之后，这两件事都是普通断言。
 *
 * @why 接口只暴露**两个有名字的方法**，不暴露裸随机源（`next(): number`）：
 *      名字表达的是**意图**（"我要一个单号随机段"/"我要一个内部 id"），
 *      随机源表达的是机制。机制一旦进端口，调用方就会开始自己拼字母表——
 *      于是"Crockford Base32"这条口径会从 shared 里漏出来散落各处。
 *
 * @limitation 一：**不做**"可预测序列"实现（如自增计数）进生产代码。
 *              测试要确定性 id，自己在 `test/helpers/` 里造替身；
 *              端口里留一个"按顺序发号"的实现，迟早有人在生产调到——
 *              而单号**明文禁止自增**（技术文档 §1：自增会泄露日销量、可被枚举）。
 * @limitation 二：本端口**不保证**跨进程唯一。唯一性的真正兜底是 DB 唯一约束
 *              （`order_no` 的冲突换新段重试属仓储层，D32 待办）；
 *              端口只负责"生成一个合法的候选"。
 * @limitation 三：`uuid()` 不承载权限。它只是内部键；对外暴露的**必须是** `order_no`
 *              （且必须校验归属，@see app/order-query-routes.ts 的归属判定）。
 *
 * @see adapters/ids.ts（真实实现）；../ports/clock.ts（同一条注入纪律的另一半）；
 *      packages/shared/src/orderNo.ts（随机段口径的唯一事实来源）
 */
export interface IdGen {
  /**
   * 订单号的 6 位随机段（Crockford Base32 大写，不含 I/L/O/U）。
   * 口径归 `shared/orderNo.ts`，本端口只负责"谁去摇"。
   */
  orderSeq(): string;

  /**
   * 内部标识符（UUID v4 字符串）。用于 `orders.id` 这类不对外暴露的键。
   */
  uuid(): string;
}
