/**
 * 职责：**时钟端口**（F10）——把"现在几点"从全局状态变成**可注入的输入**。
 *
 * @why 业务时间不能写在代码里 `new Date()`：一旦写死，所有依赖"现在"的逻辑
 *      **只能在真实时间下测试**。而恰恰是这些逻辑的边界最容易出错、也最难复现：
 *      - 订单号按 **JST 业务日**生成：UTC 15:00 前后差一秒，单号日期段就跨天；
 *      - 订单 30 分钟过期、回调宽限期：边界全靠时间；
 *      - 跨时区：服务器跑在美西（Render Oregon），业务日在日本。
 *      注入之后，这些边界是**普通测试用例**，不用等真实时间走到那一刻。
 *
 * @why 接口只有 `now()` 一个方法，且返回 `Date`：
 *      时区换算、格式化、业务日判定都是**领域规则**（在 domain 与 shared 里），
 *      端口只负责"取此刻"。把 `jstNow()` / `nowIso()` 也塞进来，等于让端口开始懂业务——
 *      那是这条边界最容易滑坡的地方。
 *
 * @limitation 一：**不做** freeze / tick 之类的测试专用方法。
 *              测试要固定时间，自己造一个 `Clock`（见 `test/helpers/fixed-clock.ts`），
 *              不要在端口里开"生产用不到"的后门——后门一旦存在就会有人在生产里用。
 * @limitation 二：`now()` 每次应返回**新的** Date 对象（实现侧约定）。
 *              返回同一个可变对象时，调用方 `d.setHours(...)` 会污染后续所有调用——
 *              这类 bug 的表现是"时间莫名其妙跳了"，极难定位。
 *
 * @see adapters/clock.ts（真实实现）；domain/order-no.ts（第一个使用者）；
 *      docs/地基搭建清单.md F10
 */
export interface Clock {
  /** 当前时刻。每次返回新的 Date 对象（见文件头 @limitation 二）。 */
  now(): Date;
}
