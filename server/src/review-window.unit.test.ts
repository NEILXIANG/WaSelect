/**
 * 职责：`review-window.ts` 的 L0 单测——截止日的解析与剩余天数。
 *
 * @why 这里的每一条都是"闸门会不会**静默失效**"的边界：解析错误若被读成"永不过期"，
 *      A7（生产审核模式忘了关）就又变成一个不会红的洞，而且看起来一切都正常。
 *      所以拒绝侧逐条列，且**放行侧也逐条列**——放行侧是"填了正确日期的人能不能正常启动"。
 */
import { describe, expect, it } from 'vitest';
import { daysUntil, parseReviewUntil, REVIEW_WINDOW_WARN_DAYS, utcDay } from './review-window.js';

describe('parseReviewUntil：放行侧（填对了必须原样收下）', () => {
  it.each([
    ['2026-11-15', '普通日期'],
    ['2026-01-01', '年初'],
    ['2026-12-31', '年末'],
    ['2024-02-29', '闰年 2 月 29 日是真的存在'],
    // 格里高利闰年的两个经典边界：整百年只有被 400 整除才是闰年
    ['2000-02-29', '2000 是闰年（能被 400 整除）'],
    ['2026-02-28', '平年 2 月最后一天'],
  ])('%s → 原样返回（%s）', (value) => {
    expect(parseReviewUntil(value)).toBe(value);
  });
});

describe('parseReviewUntil：拒绝侧（填错了必须返回 undefined，不能当成"永不过期"）', () => {
  it.each([
    ['', '空串'],
    ['2026-11-15T00:00:00Z', '带时刻：本模块只认日历日（@limitation 二）'],
    ['2026-13-01', '月份 13 不存在 → Invalid Date，比较恒 NaN 即永不过期'],
    ['2026-02-30', '2 月 30 日：形状合法但会被 Date 静默滚到 03-02'],
    ['2026-00-10', '月份 00'],
    ['2026-11-00', '日 00'],
    ['2026-02-29', '平年没有 2 月 29 日（闰年那条已放行，这里必须红）'],
    ['1900-02-29', '1900 **不是**闰年（能被 100 整除但不能被 400 整除）'],
    ['2026-11-15 ', '尾部空格'],
    ['20261115', '没有分隔符'],
    ['2026-2-3', '没有补零'],
    ['not-a-date', '完全不是日期'],
  ])('%s → undefined（%s）', (value) => {
    expect(parseReviewUntil(value)).toBeUndefined();
  });

  /**
   * @why 单独钉住"滚日期"这一支：`2026-02-30` 若不校验，产物是 `2026-03-02`——
   *      一个**看起来完全正常**的更晚日期，闸门因此被推迟 11 天且没有任何提示。
   *      这是本模块最难被发现的失效形态，值得一条专属用例。
   */
  it('2026-02-30 不得被读成 2026-03-02（Date 的静默滚动会把闸门推迟十一天）', () => {
    expect(parseReviewUntil('2026-02-30')).not.toBe('2026-03-02');
  });
});

describe('daysUntil：剩余天数（0 = 当天仍算未过期，负数 = 已过期）', () => {
  it.each([
    ['2026-11-15', '2026-11-15', 0, '截止日当天：填这天的人想的是"这天还能用"'],
    ['2026-11-15', '2026-11-16', 1, '次日'],
    ['2026-11-16', '2026-11-15', -1, '已过一天'],
    ['2026-11-15', '2026-11-12', -3, '已过三天'],
    ['2026-02-28', '2026-03-01', 1, '跨月（平年）'],
    ['2024-02-28', '2024-03-01', 2, '跨月（闰年多一天）'],
    ['2026-12-31', '2027-01-01', 1, '跨年'],
  ])('%s → %s = %i 天（%s）', (from, until, expected) => {
    expect(daysUntil(from, until)).toBe(expected);
  });
});

describe('utcDay：取 UTC 日历日', () => {
  it.each([
    ['2026-11-15T00:00:00Z', '2026-11-15', '当天零点'],
    ['2026-11-15T23:59:59Z', '2026-11-15', '当天最后一秒：仍是同一天'],
    ['2026-11-16T00:00:00Z', '2026-11-16', '次日零点'],
    // 日本时间 11-16 08:00 = UTC 11-15 23:00 → 仍是 15 日（@limitation 一 的宽容方向）
    ['2026-11-15T23:00:00Z', '2026-11-15', '日本时间次日上午之前都不算过期'],
  ])('%s → %s（%s）', (iso, expected) => {
    expect(utcDay(new Date(iso))).toBe(expected);
  });
});

describe('REVIEW_WINDOW_WARN_DAYS：提醒窗口', () => {
  /**
   * @why 钉住阈值本身而不是只钉住它的效果：这个值一旦被改成 0，
   *      "开着就每天报"会让运营把告警当噪音关掉（文件头 @why 的理由），
   *      而那比晚几天发现更贵。改它的人必须先读到这条用例。
   */
  it('是 3：最后三天才报，审核期中间不打扰', () => {
    expect(REVIEW_WINDOW_WARN_DAYS).toBe(3);
  });
});
