/**
 * 职责：列表取数失败的**页内**标记（体验审查 2026-10-15，P2-4）。
 *
 * @why 四个列表页（订单 / 商品 / 客户 / 运营日志）此前"失败只走 Toast"：Toast 在右下角、
 *      与表格没有任何视觉关联，而失败时**列表保留上一次的结果**（清空列表会让运营失去手上的上下文）。
 *      于是运营看到的是一份可能已过期的数据，却没有任何地方告诉他"这不是最新的"——
 *      照着它勾选批量发货、导出 CSV，导出的就是过期数据。
 * @why 抽成组件而不是四个页面各写一句：这句话要说清三件事（没刷新 / 下面是旧的 / 怎么重试），
 *      各写一遍必然各漂一次；而"重试方式"只有一处可能不同（有没有「刷新」按钮），做成参数。
 * @why 文案里**明说"下面显示的是上一次成功加载的结果"**而不是只说"加载失败"：
 *      失败时列表是有内容的，只说"失败"会让运营以为列表是空的、或以为刚才的勾选丢了。
 * @limitation 只做"标记"，不含重试动作：重试入口是各页自己的「刷新」/「查询」按钮，
 *             组件不知道也不该知道那一页怎么重新取数。
 */
export interface ListErrorProps {
  /** 这一屏的名字（「订单列表」/「操作记录」…）。 */
  what: string;
  /**
   * 页内重试按钮的文案（**只有那个按钮点了真的会重新取数才传**）。
   * @why '' = 不给具体按钮：多数列表页的「搜索」在关键词没变时写回同一串参数、地址不变 ⇒ 不会重新取数。
   */
  retry?: string;
  /**
   * 下面有没有上一次成功加载的数据（四天提交复查 2026-10-16）。
   * @why 首次取数就失败时列表是空的，再说"下面显示的是上一次成功加载的结果"就是一句不成立的话。
   */
  stale: boolean;
}

export function ListError({ what, retry = '', stale }: ListErrorProps) {
  return (
    <p className="error" role="status">
      {stale
        ? `${what}没能刷新，下面显示的是上一次成功加载的结果（可能已过期）。`
        : `${what}没能加载。`}
      {retry === '' ? '请翻页或改一下筛选重新加载。' : `请点「${retry}」重试。`}
    </p>
  );
}
