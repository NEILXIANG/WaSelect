/**
 * 职责：组件样板页（F14）——把已建的基础组件**每一种状态**摆在一页上。
 *
 * @why 组件级测试（simulate）能钉住结构与文案，但钉不住**视觉**，也钉不住
 *      "真机基础库"的行为（最典型的是原生 `disabled` 到底挡不挡点击）。
 *      这两件事只能靠人打开看——而"人打开看"需要一个**把所有状态摆齐**的页面，
 *      否则每次验收都要临时改代码去凑状态，最后就不验了。
 *      这一页就是那个固定的验收面（对应 L4 人工检查项）。
 *
 * @why 刻意把"坏状态"也摆在页面上（漏传价格那个 `<ws-price />`）：
 *      它每次打开都会在控制台报一条错——**这是想要的效果**，不是 bug。
 *      "漏传价格时是空白而不是 `¥0`"这条性质，肉眼在页面上看一眼比读注释可靠。
 *
 * @limitation 一：这一页**不是产品页面**，只做展示，不做交互打磨；
 *              它随组件一起演进，组件加了状态就在这里加一行。
 * @limitation 二：点击计数只用于证明"loading / disabled 的按钮点了不计"，
 *              不做持久化——页面重建归零是刻意的，免得误把它当成业务数据。
 *
 * @see ../../components/ws-price/index.js；../../components/ws-button/index.js；
 *      ../showcase-guard.unit.test.ts（断言本页登记了每一个已建组件）
 */
Page({
  data: {
    /** 有效点击次数（loading / disabled 的按钮点了不该增加）。 */
    taps: 0,
  },

  onCount() {
    this.setData({ taps: this.data.taps + 1 });
  },
});
