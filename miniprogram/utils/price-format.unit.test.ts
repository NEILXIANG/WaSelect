/**
 * 职责：金额展示格式化的单测（F14 第一个基础组件的前置）。
 *
 * @why 格式化看着是"小事"，但它的错误形态是**静默且跨页面**的：
 *      `¥1234` 与 `¥1,234` 都能读，而"不同页面长得不一样"没有任何报错；
 *      `¥0` 与"不显示"之间隔着一整个"用户以为免费"的距离。
 *      所以三条边界必须各自有用例：千分位、四舍五入方向、坏数据必须响亮失败。
 *
 * @how 断言**具体字符串**而不是"包含数字"：包含式断言在少了分隔符时照样绿。
 */
import { describe, expect, it } from 'vitest';
import { formatJpy } from './price-format.js';

describe('千分位', () => {
  it('四位数加一个分隔符', () => {
    expect(formatJpy(1234)).toBe('¥1,234');
  });

  it('整千位不加尾部空组（`¥1,000` 不是 `¥1,000,`）', () => {
    expect(formatJpy(1000)).toBe('¥1,000');
  });

  it('三位数不加分隔符', () => {
    expect(formatJpy(123)).toBe('¥123');
  });

  it('大金额每一组三个数字', () => {
    expect(formatJpy(12345678)).toBe('¥12,345,678');
  });

  it('0 → `¥0`（不是空串，也不是占位符）', () => {
    expect(formatJpy(0)).toBe('¥0');
  });
});

describe('负数（退款 / 折扣会真的出现负金额）', () => {
  it('负号在货币符号**前面**（`-¥1,234`，不是 `¥-1,234`）', () => {
    expect(formatJpy(-1234)).toBe('-¥1,234');
  });

  it('⚠️ 四舍五入到 0 的负数不带负号——`-¥0` 看起来像出错了', () => {
    expect(formatJpy(-0.4)).toBe('¥0');
  });
});

describe('小数：四舍五入而不是截断（@limitation 二）', () => {
  it('< 0.5 舍', () => {
    expect(formatJpy(1234.4)).toBe('¥1,234');
  });

  it('>= 0.5 入', () => {
    expect(formatJpy(1234.5)).toBe('¥1,235');
  });

  it('⚠️ 含税价 ×1.1 的小数必须入（`Math.floor` 会**每次都少 1 円**）', () => {
    // @why 少 1 円听起来微不足道，但它是**系统性**的：每笔都少，在账上会累积成差额，
    //      而排查方向会去看税率、去看汇率，没人会怀疑是格式化函数。
    //      1235 × 1.1 = 1358.5 → round 给 1359，floor 给 1358
    expect(formatJpy(1235 * 1.1)).toBe('¥1,359');
  });
});

describe('坏数据必须响亮失败（@limitation 一）', () => {
  it.each([
    ['NaN', Number.NaN],
    ['Infinity', Number.POSITIVE_INFINITY],
    ['-Infinity', Number.NEGATIVE_INFINITY],
    ['undefined', undefined],
    ['null', null],
    ['字符串', '1234'],
    ['对象', {}],
  ])('%s → 抛错（不给默认值、不显示占位符）', (_name, value) => {
    // @why 静默给 `¥0` 的后果是"用户以为免费"；静默显示占位符的后果是"这个商品没有价格"。
    //      两者都比"组件渲染失败 + 控制台一条明确报错"贵。
    // ⚠️ 这里的强转是**刻意**的：该函数在运行时要能挡住任何类型，
    //    所以用例必须真的把非数字传进去——类型层面装作是数字，是为了把"运行时校验"测出来。
    expect(() => formatJpy(value as unknown as number)).toThrow(/金额必须是有限数/);
  });
});
