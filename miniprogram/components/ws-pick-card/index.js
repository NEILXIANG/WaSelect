/**
 * 职责：**编辑精选卡片**（S4 从设计原型迁入）——图 → 产地/匠人 → 名 → why → 价。
 *
 * @why 卡片结构**固定**为这个顺序，且 `why` 在名字**下面**、价格**上面**：
 *      让"为什么值得"成为"要不要看价格"之前的那一道闸——先看值不值，再看多少钱。
 *      反过来放（名 → 价 → why）会变成"先看贵不贵"，那又是卖场。
 * @why 产地与匠人写成一行小字放在最上：它回答的是"谁做的"。
 *      对这批用户来说，"来源可信"比"参数齐全"更能促成决定。
 *
 * @why **扁平属性**而不是像原型那样收一个 `item` 对象：
 *      原型是同一份 mock 数据在几个页面间传来传去，`item` 很顺手；
 *      生产这边的数据来自 `GET /products`（列表）与 vm 的映射结果，
 *      收对象会让"页面必须构造出与 vm 输出逐字一致的键"变成一条看不见的耦合——
 *      键名一改，卡上就静默少一块内容（不报错，因为属性缺失在小程序里是合法的）。
 *      扁平属性让"少传了哪个"在 wxml 上一眼可见。
 *
 * @limitation 一：**`why` 为空时整卡降级**（不渲染 why 块），不报错、不用通用话术顶上。
 *              @why 这是 AJ-296① 的降级口径，也是本组件存在的理由之一：
 *              必填 why 会逼运营"随便填一句"交差，首页立刻出现一批假文案，
 *              而"高品质""匠心工艺"这类话术比留白更伤——留白只是没有信息，
 *              话术是**假的**信息，而且会让人对整个品牌的判断力打折。
 * @limitation 二：图区固定用 **scene 比例（`--ws-scene-h`，4:3；2026-10-12 用户选定，原为 260rpx ≈ 2.6:1）**而不是原型的正方形。
 *              @why 生产当前**没有商品图**（`images` 恒为空数组），全宽的正方形
 *              会是一整屏高（750rpx）的空白块，把下面的 why 挤出首屏——
 *              那比"没有图"还糟：用户看到的第一屏只有一块空。
 *              ⚠️ 这是**比例**的降级不是**结构**的降级：等图到位后把
 *              `ws-media--scene` 换成 `ws-media--square` 即可（两档都是设计体系已有的档位），
 *              不需要改组件结构。
 * @limitation 三：价格**只收 `priceJpy` 整数**，副行美元文案由页面传 `usdText`。
 *              @why 金额的换算与格式化归 `ws-price` 组件（唯一的日元格式化实现），
 *              本组件若自己拼 `¥{{price}}` 就会出现第二份格式化——
 *              而第二份的下场通常是"千分位没加"。
 * @limitation 四：整卡可点 → `hover-class` 必须给（原型也是这么写的）。
 *              少了它，"点到了没有"全靠猜，用户会连点两次。
 *
 * @see ../ws-price/index.js（金额格式化的唯一实现）
 * @see ../../../waselect-design/components/pick-card（S4 迁移源）
 */
Component({
  /**
   * ⚠️ `styleIsolation: 'apply-shared'`：**必须**给，不是风格偏好。
   *
   * @why 小程序自定义组件的默认隔离是 `isolated`——**除继承属性（font / color）外，
   *      `app.wxss` 与页面的样式对组件内部一律无效**。而本组件的 wxml 直接用了
   *      设计体系的基础类（`.ws-media` / `.ws-media--scene` / `.ws-title` / `.ws-tag`），
   *      它们全部定义在 app.wxss 里。默认隔离下这些类**一个都不会生效**：
   *      图容器没有高度（图片塌成 0）、标签没有底色、标题不是衬线——
   *      而编译不报任何错，只有真机上看一眼才发现（L4）。
   *      `apply-shared` 让 app.wxss / 页面的样式进到组件内，基础类才成立。
   * @why 不用 `shared`（双向）：`shared` 会让**组件自己的样式反过来影响页面**，
   *      于是 `.ws-pick__flag` 这类内部类名一旦与页面撞名就会改到页面——
   *      我们只需要"外面的基础类进来"这一个方向。
   * @limitation 代价：页面样式也能进来，页面里若定义了同名类会覆盖组件外观。
   *      这正是"必须全部用 `ws-pick__*` 前缀"的原因（本文件 wxss 文件头有同一条说明）。
   */
  options: { styleIsolation: 'apply-shared' },

  properties: {
    /** 商品图 URL；空串 = 不渲染 `<image>`（空 src 在真机上是破图占位）。 */
    image: { type: String, value: '' },
    /** 产地 / 工房 / 匠人署名。空串 = 不渲染这一行。 */
    maker: { type: String, value: '' },
    /** 商品名（衬线）。 */
    name: { type: String, value: '' },
    /** 编辑口径的"为什么值得买"。空串 = **整卡降级**（@see @limitation 一）。 */
    why: { type: String, value: '' },
    /**
     * 日元单价（整数円）。
     * ⚠️ `type: null` 且不给默认值（P1-6）：原来是 `{ type: Number, value: 0 }`，
     *    列表数据漏了 `price_jpy` 时卡片照样显示 `0 円`——用户读成"免费"。
     *    不做类型转换后漏传就是 null，交给 ws-price 响亮失败（空白 + 控制台报错）。
     * @see ../ws-price/index.js @limitation 一（同一条理由，实测过 Number 会被补 0）
     */
    priceJpy: { type: null },
    /** 副行换算文案（如"约 $23.40"）；由页面算好传进来。空串 = 不渲染。 */
    usdText: { type: String, value: '' },
    /** 库存；≤5 时显示"仅剩 N 件"角标（0 时不显示——售罄由页面另给标记）。 */
    stock: { type: Number, value: -1 },
    /** 展示标签（自由文案）。空数组 = 不渲染标签区。 */
    tags: { type: Array, value: [] },
  },

  methods: {
    onTap() {
      // ⚠️ 不带 detail：本组件没有"点了卡上哪个位置"这类信息可给，
      //    把坐标透传出去只会让页面以为有内容可看（与 ws-button 同口径）。
      this.triggerEvent('tap');
    },
  },
});
